def main():
    added = 0
    skipped = 0
    failed = 0

    with get_session() as session:
        for src, tgt in PREREQUISITES:
            result = session.run(
                """
                MATCH (a:Course {courseId: $src}), (b:Course {courseId: $tgt})
                MERGE (a)-[r:PREREQUISITE_OF]->(b)
                RETURN r IS NOT NULL AS ok, a.nameKr AS src_name, b.nameKr AS tgt_name
                """,
                src=src, tgt=tgt,
            )
            record = result.single()
            if record:
                print(f"  ✓ {record['src_name']} → {record['tgt_name']}")
                added += 1
            else:
                print(f"  ✗ 과목 없음: {src} → {tgt}")
                failed += 1

    print(f"\n완료: {added}개 추가 / {failed}개 실패 (과목 없음)")


if __name__ == "__main__":
    main()
